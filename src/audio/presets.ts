import type { EffectCategory, EffectPreset, EffectRecipe } from "./types";

export const CATEGORIES: EffectCategory[] = [
  "Essentials",
  "Characters",
  "Spaces",
  "Musical",
  "Creative",
];
const colors: Record<EffectCategory, string> = {
  Essentials: "#90b7a4",
  Characters: "#e69b75",
  Spaces: "#9c9fe6",
  Musical: "#d5a4df",
  Creative: "#85bcd1",
};
function preset(
  id: string,
  name: string,
  category: EffectCategory,
  icon: string,
  description: string,
  recipe: EffectRecipe,
  tags: string[],
): EffectPreset {
  return {
    id,
    name,
    category,
    icon,
    description,
    recipe,
    tags,
    color: colors[category],
  };
}

